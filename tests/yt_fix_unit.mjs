import { swapBadYouTube, splitYouTube } from "../frontend/src/lib/youtube.js";
let pass = 0, fail = 0;
const t = (ok, msg) => { ok ? pass++ : fail++; console.log(ok ? "PASS" : "FAIL", msg); };
const lines = ["1. Knots", "Bowline - https://www.youtube.com/watch?v=fake1", "Cleat hitch https://youtu.be/dQw4w9WgXcQ", "2. Anchoring", "Set the anchor (https://www.youtube.com/watch?v=fake2)", "https://www.youtube.com/watch?v=fake3"];
const bad = [{ line: 1, url: "https://www.youtube.com/watch?v=fake1" }, { line: 4, url: "https://www.youtube.com/watch?v=fake2" }, { line: 5, url: "https://www.youtube.com/watch?v=fake3" }];
const s = swapBadYouTube(lines, bad);
t(s[1] === "Bowline https://www.youtube.com/results?search_query=Bowline", "search swap " + s[1]);
t(s[4] === "Set the anchor https://www.youtube.com/results?search_query=Set%20the%20anchor", "brackets tidied " + s[4]);
t(s[2] === lines[2] && s[0] === lines[0] && s[3] === lines[3], "good links and headings untouched");
t(s.length === 5, "link-only line dropped");
t(splitYouTube(s[1]).some((p) => typeof p !== "string"), "search link renders as YouTube pill");
t(JSON.stringify(swapBadYouTube(lines, [])) === JSON.stringify(lines), "no bad links -> unchanged");
console.log(`TOTAL ${pass} passed, ${fail} failed`);
